#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const artifactsRoot = path.join(repoRoot, 'artifacts', 'course-geometry')
const outputPath = path.join(repoRoot, 'src', 'courseGeometry', 'generatedRouteHoleHeadings.ts')

const courses = {}

for (const entry of fs.readdirSync(artifactsRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const manifestPath = path.join(artifactsRoot, entry.name, 'validation-v1.json')
  if (!fs.existsSync(manifestPath)) continue

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  if (typeof manifest.courseId !== 'string' || !Array.isArray(manifest.holes)) continue

  const headings = Array.from({ length: 18 }, () => null)
  for (const hole of manifest.holes) {
    const holeNumber = Number(hole?.hole)
    const heading = Number(hole?.headingDegreesTrue)
    if (!Number.isInteger(holeNumber) || holeNumber < 1 || holeNumber > 18) continue
    if (!Number.isFinite(heading)) continue
    headings[holeNumber - 1] = heading
  }

  if (headings.every((heading) => typeof heading === 'number')) {
    courses[manifest.courseId] = headings
  }
}

const serialized = JSON.stringify(courses, null, 2)
const source = `// AUTO-GENERATED by tools/generate-course-registration-index.mjs.\n// Do not hand-edit; the cached validation manifests are the source of truth.\n\nexport const routeHoleHeadingDegreesTrue: Readonly<Record<string, readonly number[]>> = ${serialized}\n\nexport const getRouteHoleHeadingDegreesTrue = (courseId: string, holeNumber: number): number | null => {\n  const headings = routeHoleHeadingDegreesTrue[courseId]\n  const heading = headings?.[Math.max(1, Math.min(18, Math.round(holeNumber))) - 1]\n  return typeof heading === 'number' && Number.isFinite(heading) ? heading : null\n}\n`

fs.writeFileSync(outputPath, source, 'utf8')
console.log(`Generated route headings for ${Object.keys(courses).length} courses -> ${path.relative(repoRoot, outputPath)}`)
