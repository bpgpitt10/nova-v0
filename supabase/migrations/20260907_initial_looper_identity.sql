-- Users may only confirm their own allow-list record. Admin management can use
-- the Supabase dashboard/service role initially, and a tiny Looper admin UI later.
create policy "allowed users can read own allowlist row"
  on public.allowed_users for select
  to authenticated
  using (
    lower(email::text) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );

create policy "users can read own profile"
  on public.profiles for select
  to authenticated
  using (id = auth.uid() and public.is_allowed_user());

create policy "users can update own profile"
  on public.profiles for update
  to authenticated
  using (id = auth.uid() and public.is_allowed_user())
  with check (id = auth.uid() and public.is_allowed_user());

create policy "users own bags"
  on public.bags for all
  to authenticated
  using (user_id = auth.uid() and public.is_allowed_user())
  with check (user_id = auth.uid() and public.is_allowed_user());

create policy "users own sessions"
